#!/usr/bin/env python3
"""Encode the game's keyed sprites as KTX2 (src/keyedSpriteBakes.js).

Input is the export of tests/e2e/probes/keyed-sprite-bake.spec.js: each
sprite exactly as the runtime keyer left it, and an index of their keys
(path::threshold::crop). Each one is
  - bled: transparent pixels take the colour of the nearest opaque one, so
    mipmaps don't pull dark fringes in from the keyed-out backdrop;
  - resized to sides in multiples of four (block-compressed uploads need it);
  - flipped bottom-up (compressed uploads can't flip, sprites sample with v up);
  - encoded as UASTC KTX2 with alpha and mipmaps (sRGB),
to public/3d/runtime/sprites/, and src/data/keyedSpriteBakes.js is rewritten
with each key's file and the sha1 of the source PNG it was keyed from. A
sprite whose source is unchanged is skipped; src/keyedSpriteBakes.test.js
fails when a source changes without a rebake.

  python3 scripts/art/build_keyed_sprite_ktx2.py --basisu /path/to/basisu --export /tmp/keyed
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / 'public/3d/runtime/sprites'
MANIFEST = ROOT / 'src/data/keyedSpriteBakes.js'
HEADER = """// Generated by scripts/art/build_keyed_sprite_ktx2.py. Do not edit by hand.
// Keyed sprite (path::threshold::crop) -> its baked KTX2 and the sha1 of the
// source PNG it was keyed from.
"""


def read_manifest():
    if not MANIFEST.exists():
        return {}
    text = MANIFEST.read_text()
    match = re.search(r'Object\.freeze\((\{.*\})\);', text, re.S)
    return json.loads(match.group(1)) if match else {}


def write_manifest(entries):
    body = json.dumps(dict(sorted(entries.items())), indent=4)
    MANIFEST.write_text(f'{HEADER}export const KEYED_SPRITE_BAKES = Object.freeze({body});\n')


def slug_for(key):
    path, threshold, crop = key.split('::')
    stem = re.sub(r'[^a-z0-9]+', '_', Path(path).stem.lower()).strip('_')
    crop_tag = re.sub(r'[^0-9]', '', crop) or '0'
    folder = re.sub(r'[^a-z0-9]+', '_', str(Path(path).parent).lower()).strip('_')
    return f"{folder + '__' if folder else ''}{stem}-t{threshold}-c{crop_tag}"


def bleed(rgba):
    alpha = rgba[..., 3]
    clear = alpha == 0
    if not clear.any() or clear.all():
        return rgba
    _, (rows, cols) = ndimage.distance_transform_edt(clear, return_indices=True)
    out = rgba.copy()
    out[..., :3] = rgba[rows, cols, :3]
    out[..., 3] = alpha
    return out


def multiple_of_four(size):
    return max(4, int(round(size / 4)) * 4)


def ktx2_size(path):
    header = path.read_bytes()[:28]
    return int.from_bytes(header[20:24], 'little'), int.from_bytes(header[24:28], 'little')


def encode(basisu, exported, target):
    rgba = bleed(np.asarray(Image.open(exported).convert('RGBA')))
    # Block-compressed uploads need sides in multiples of four: a 627 x 627
    # bake failed glTexStorage on the GPU and drew nothing. Resizing (not
    # padding) keeps the whole sprite on the same UVs.
    height, width = rgba.shape[:2]
    size = (multiple_of_four(width), multiple_of_four(height))
    if size != (width, height):
        rgba = np.asarray(Image.fromarray(rgba, 'RGBA').resize(size, Image.LANCZOS))
    prepared = np.ascontiguousarray(np.flipud(rgba))
    with tempfile.TemporaryDirectory() as work:
        source = Path(work) / 'sprite.png'
        Image.fromarray(prepared, 'RGBA').save(source)
        subprocess.run([basisu, '-uastc', '-uastc_level', '2', '-uastc_rdo_l', '1.0', '-mipmap', '-ktx2',
                        '-ktx2_zstandard_level', '18', str(source), '-output_file', str(target)],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, cwd=work)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--basisu', required=True)
    parser.add_argument('--export', required=True, help='keyed-sprite-bake probe output folder')
    parser.add_argument('--jobs', type=int, default=6)
    parser.add_argument('--force', action='store_true')
    args = parser.parse_args()
    export = Path(args.export)
    index = json.loads((export / 'index.json').read_text())
    manifest = read_manifest()
    OUT.mkdir(parents=True, exist_ok=True)

    def run(entry):
        key = entry['key']
        source = ROOT / 'public' / key.split('::')[0].lstrip('/')
        sha1 = hashlib.sha1(source.read_bytes()).hexdigest()
        target = OUT / f'{slug_for(key)}.ktx2'
        url = f'/3d/runtime/sprites/{target.name}'
        known = manifest.get(key)
        if not args.force and known and known['sha1'] == sha1 and target.exists() \
                and all(side % 4 == 0 for side in ktx2_size(target)):
            return key, known, 'skip'
        encode(args.basisu, export / entry['file'], target)
        if any(side % 4 for side in ktx2_size(target)):
            raise SystemExit(f'{target}: sides must be multiples of four, got {ktx2_size(target)}')
        return key, {'url': url, 'sha1': sha1}, f'{target.stat().st_size / 1e6:.2f} MB'

    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for key, record, note in pool.map(run, index):
            manifest[key] = record
            if note != 'skip':
                print(f'[sprites] {key} -> {record["url"]} ({note})', flush=True)
    write_manifest(manifest)
    print(f'[sprites] manifest: {len(manifest)} baked sprites')
    return 0


if __name__ == '__main__':
    sys.exit(main())
