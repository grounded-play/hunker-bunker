#!/usr/bin/env node
/* global process, console */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEEP_RELIC_CACHE_DROP_TABLE } from '../server/lootTables.js';
import { generatedTextMatches } from './generated-text.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA_PATH = path.join(ROOT, 'steam/inventory_schema_hunker_bunker.json');
const OUTPUT_PATH = path.join(ROOT, 'src/data/steamItemCatalog.js');
const RARITY_BY_COLOR = Object.freeze({
    '94a3b8': 'common',
    '00c8ff': 'rare'
});

function parseTags(raw = '') {
    return Object.fromEntries(String(raw).split(';').map((part) => part.split(':', 2)).filter((pair) => pair.length === 2));
}

function rarityForItem(entry) {
    return parseTags(entry.tags).rarity ?? RARITY_BY_COLOR[String(entry.name_color ?? '').toLowerCase()] ?? 'common';
}

export function buildRendererCatalog(schema) {
    return Object.fromEntries(schema.items
        .filter((entry) => entry.type === 'item' && entry.icon_url)
        .map((entry) => {
            const slug = path.basename(new URL(entry.icon_url).pathname, '.png');
            return [entry.itemdefid, {
                itemdefid: entry.itemdefid,
                name: entry.name,
                rarity: rarityForItem(entry),
                desc: entry.description,
                tradable: Boolean(entry.tradable),
                marketable: Boolean(entry.marketable),
                img: entry.icon_url,
                localImg: `/economy/${slug}.png`,
                localImgLarge: `/economy/${slug}_large.png`
            }];
        }));
}

export function validateResolverOdds(schema, dropTable = DEEP_RELIC_CACHE_DROP_TABLE) {
    const resolver = schema.items.find((entry) => entry.itemdefid === 4002);
    if (!resolver?.bundle) throw new Error('ItemDef 4002 resolver bundle is missing.');
    const parts = resolver.bundle.split(',').map(Number);
    const configured = [];
    for (let index = 0; index < parts.length; index += 2) {
        configured.push({ itemdefid: parts[index], weight: parts[index + 1] });
    }
    const expected = dropTable.map(({ itemdefid, weight }) => ({ itemdefid, weight }));
    if (JSON.stringify(configured) !== JSON.stringify(expected)) {
        throw new Error(`ItemDef 4002 bundle does not match DEEP_RELIC_CACHE_DROP_TABLE.`);
    }
    return true;
}

export function renderCatalogModule(catalog) {
    return `// GENERATED by scripts/build-steam-item-catalog.js from the publishable Steam schema.
// Do not edit by hand. Server-only generators, recipes, prices, and bundles are excluded.
const catalog = ${JSON.stringify(catalog, null, 4)};

for (const entry of Object.values(catalog)) Object.freeze(entry);
export const STEAM_ITEM_CATALOG = Object.freeze(catalog);
`;
}

export function buildSteamItemCatalog({
    schemaPath = SCHEMA_PATH,
    outputPath = OUTPUT_PATH,
    check = false
} = {}) {
    const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
    validateResolverOdds(schema);
    const output = renderCatalogModule(buildRendererCatalog(schema));
    if (check) {
        const current = fs.readFileSync(outputPath, 'utf8');
        if (!generatedTextMatches(current, output)) {
            throw new Error(`${path.relative(ROOT, outputPath)} is stale; run npm run steam:item-catalog.`);
        }
    } else {
        fs.writeFileSync(outputPath, output, 'utf8');
    }
    return { itemCount: Object.keys(buildRendererCatalog(schema)).length, outputPath };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    try {
        const result = buildSteamItemCatalog({ check: process.argv.includes('--check') });
        console.log(`[steam-item-catalog] ${process.argv.includes('--check') ? 'current' : 'wrote'} ${path.relative(ROOT, result.outputPath)} (${result.itemCount} items)`);
    } catch (error) {
        console.error(`[steam-item-catalog] ${error?.message ?? error}`);
        process.exitCode = 1;
    }
}
