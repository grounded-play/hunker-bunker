#!/usr/bin/env node
// Writes server/tradeUpCatalog.js: the items the Smelter trades up and the
// Dispensary redeems, with their rarity. The backend image copies only
// server/, so it cannot read the client catalog; this file is its copy.
// src/tradeUpCatalog.parity.test.js fails if the two drift.
//
//   node scripts/build-trade-up-catalog.js          # write
//   node scripts/build-trade-up-catalog.js --check  # verify only
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { deriveTradeUpItems } from '../src/tradeUpCollection.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'server/tradeUpCatalog.js');

const items = deriveTradeUpItems();
const body = Object.entries(items).map(([id, rarity]) => `    ${id}: '${rarity}'`).join(',\n');
const text = `// GENERATED by scripts/build-trade-up-catalog.js from the client item catalog.
// Do not edit by hand. The Season 0 cosmetic collection (itemdefs 4100-4153,
// equippable kinds only): what the Smelter consumes and grants, and what the
// Dispensary redeems. Keys, caches, shards, reagents, achievement and promo
// items and season rewards are outside it, so a trade-up can never burn them.
// Imported by the backend (server/steamTradeUp.js) and the client
// (src/craftingMatrix.js), so both judge an item the same way.

export const TRADE_UP_ITEMS = Object.freeze({
${body}
});
`;

if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
        console.error('[trade-up-catalog] server/tradeUpCatalog.js is stale; run node scripts/build-trade-up-catalog.js');
        process.exit(1);
    }
    console.log(`[trade-up-catalog] ok (${Object.keys(items).length} items)`);
} else {
    fs.writeFileSync(OUT, text);
    console.log(`[trade-up-catalog] wrote ${Object.keys(items).length} items`);
}
